/* ล็อกลำดับศัพท์บทที่ 16 ให้ตรงหนังสือ 汉语教程 第一册 下 หน้า 3-4

   ผู้เรียนนับการ์ดเทียบกับเลขข้อในหนังสือ (เคยถามว่า "少 อยู่คำที่เท่าไหร่")
   ถ้าใครแทรกคำใหม่กลางลิสต์ ลำดับจะเลื่อนหมดแล้วเทียบกับหนังสือไม่ได้อีก
   → คำที่หนังสือไม่ลิสต์ต้องต่อท้ายเท่านั้น ห้ามแทรกกลาง */
import { describe, expect, it } from 'vitest'
import { lessons } from './lessons'

/** ข้อ 1-32 ของหนังสือ + หัวข้อย่อย 4 คำ (时候 网 收 电视) แทรกใต้ข้อแม่ตามที่หนังสือพิมพ์ */
const BOOK = [
  '现在', '跟', '一起', '咱们', '走', '常', '借',
  '有时候', '时候',        // ข้อ 8 + หัวข้อย่อย
  '上网', '网',            // ข้อ 9 + หัวข้อย่อย
  '查', '资料', '总', '宿舍', '安静', '晚上', '复习', '课文', '预习', '生词', '或者', '练习',
  '聊天儿', '发', '微信',
  '收发', '收',            // ข้อ 25 + หัวข้อย่อย
  '邮件', '电影',
  '电视剧', '电视',        // ข้อ 28 + หัวข้อย่อย
  '休息', '公园', '超市', '东西',
]

/** คำที่โผล่ในบทสนทนาของบทนี้ แต่หนังสือไม่ได้ลิสต์เป็นศัพท์ใหม่
    เก็บไว้เพราะถ้าไม่มี ตัวตรวจคำแปลไทยจะดึงคำหลักของประโยคที่ใช้คำพวกนี้ไม่ได้ */
const EXTRA = ['少', '玩儿', '但']

const L16 = lessons[15]

describe('ศัพท์บทที่ 16', () => {
  it('ลำดับ 36 คำแรกต้องตรงหนังสือเป๊ะ', () => {
    expect(L16.vocab.slice(0, BOOK.length).map((w) => w.zh)).toEqual(BOOK)
  })

  it('คำที่หนังสือไม่ลิสต์ต้องอยู่ท้ายสุด ไม่แทรกกลาง', () => {
    expect(L16.vocab.slice(BOOK.length).map((w) => w.zh)).toEqual(EXTRA)
  })

  it('ไม่มีคำอื่นนอกจาก 2 กลุ่มนี้ และไม่ซ้ำ', () => {
    const zh = L16.vocab.map((w) => w.zh)
    expect(zh).toHaveLength(BOOK.length + EXTRA.length)
    expect(new Set(zh).size).toBe(zh.length)
  })

  it('ทุกคำต้องมี py / th / en / thr ครบ', () => {
    const bad = L16.vocab.filter((w) => !w.py || !w.th || !w.en || !w.thr)
    expect(bad.map((w) => w.zh)).toEqual([])
  })

  it('คำเสริมทุกคำต้องโผล่ในบทสนทนาจริง (ไม่งั้นไม่มีเหตุผลที่จะเก็บไว้)', () => {
    const text = L16.dialogue.map((d) => ('sec' in d ? '' : d.zh)).join('')
    expect(EXTRA.filter((zh) => !text.includes(zh))).toEqual([])
  })
})
